export type Ingredient = {
  id: string;
  name: string;
  category: string;
  /** grams in one standard cup measure */
  cupGrams: number;
  /** per 100 g */
  carbs: number;
  protein: number;
  fats: number;
  gi: number;
  note?: string;
};

/** [name, cupGrams, carbs, protein, fats, gi] per 100 g */
type Row = [string, number, number, number, number, number];

function slug(name: string): string {
  return name
    .toLowerCase()
    .replace(/%/g, "pct")
    .trim()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");
}

function group(category: string, rows: Row[]): Ingredient[] {
  return rows.map(([name, cupGrams, carbs, protein, fats, gi]) => ({
    id: slug(name),
    name,
    category,
    cupGrams,
    carbs,
    protein,
    fats,
    gi,
  }));
}

